package com.smarttask.user.entity;

/**
 * Represents the roles available in the Smart Task Management System.
 *
 * <p>Roles define the permissions and access level of a user within
 * the application.</p>
 */
public enum Role {

    /**
     * Standard application user.
     */
    USER,

    /**
     * Administrator with elevated privileges.
     */
    ADMIN
}